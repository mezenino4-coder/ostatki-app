# -*- coding: utf-8 -*-
"""Нормализация кодов деталей для матчинга.

Проблема: OCR читает буквенные коды (АМ, НПО, Ш...) то кириллицей, то
латиницей. Чтобы код из скрина совпал с кодом в базе, приводим обе стороны
к одной канонической форме: латиница-эквивалент + верхний регистр +
схлопывание пробелов.
"""

# Кириллица -> латиница-эквивалент (визуально похожие буквы).
CYR_TO_LAT = {
    "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M", "Н": "H",
    "О": "O", "Р": "P", "С": "C", "Т": "T", "У": "Y", "Х": "X",
    "а": "A", "в": "B", "е": "E", "к": "K", "м": "M", "н": "H",
    "о": "O", "р": "P", "с": "C", "т": "T", "у": "Y", "х": "X",
}

# Кириллические буквы без латинского близнеца оставляем как есть,
# но приводим к верхнему регистру (Ш, Ж, Ц, Ч, Щ, Ю, Я, Э, Ы, Ь, Ъ, Ё).
_CYR_KEEP = {
    "а": "А", "б": "Б", "в": "В", "г": "Г", "д": "Д", "е": "Е",
    "ж": "Ж", "з": "З", "и": "И", "й": "Й", "л": "Л", "н": "Н",
    "п": "П", "ф": "Ф", "ц": "Ц", "ч": "Ч", "ш": "Ш", "щ": "Щ",
    "ъ": "Ъ", "ы": "Ы", "ь": "Ь", "э": "Э", "ю": "Ю", "я": "Я",
    "ё": "Ё", "у": "У", "к": "К", "е": "Е",
}


def normalize_code(text: str) -> str:
    """Привести код детали к канонической форме для сравнения."""
    if not text:
        return ""
    out = []
    for ch in text:
        if ch in CYR_TO_LAT:
            out.append(CYR_TO_LAT[ch])
        elif "а" <= ch <= "я" or "А" <= ch <= "Я" or ch in "Ёё":
            # остальная кириллица -> верхний регистр
            out.append(ch.upper())
        else:
            out.append(ch.upper())
    s = "".join(out)
    # убрать ВСЕ пробелы (как в проверенном plan_app) — код каноничен без них
    return s.replace(" ", "")


def first_code_token(name: str) -> str:
    """Первый токен наименования, содержащий цифру — это код детали."""
    import re
    for tok in (name or "").split():
        if re.search(r"\d", tok):
            return tok
    return (name or "").split()[0] if (name or "").strip() else ""


def parse_qty(text: str) -> float | None:
    """Разобрать количество вида '45,000' / '1,000' / '2' в float."""
    if not text:
        return None
    t = text.strip().replace(" ", "").replace("\u00a0", "")
    t = t.replace(",", ".")
    # отбросить мусорные символы (скобки, буквы ед. измерения)
    import re
    m = re.search(r"-?\d+(?:\.\d+)?", t)
    if not m:
        return None
    try:
        return float(m.group(0))
    except ValueError:
        return None
